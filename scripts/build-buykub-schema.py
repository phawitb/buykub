"""Build a standalone bootstrap for a new, isolated BUYKUB schema."""
from pathlib import Path
import re

root = Path(__file__).resolve().parents[1]
base = (root / 'supabase/schema.sql').read_text()
# Storage is shared across schemas and is deliberately excluded from this bootstrap.
base = base[:base.index('-- Storage ---')] + base[base.index('-- Product-key inventory'):]
base = base.replace('create extension if not exists "pgcrypto";', '')
parts = [base]
for name in ['20260725223000_booking_calendar_sync.sql', '20260727110000_stripe_checkout.sql']:
    parts.append((root / 'supabase/migrations' / name).read_text())
sql = '\n'.join(parts)
sql = sql.replace('public.', 'buykub.').replace('set search_path = public', 'set search_path = buykub')
# Scope constraint checks to the isolated schema, even if the legacy app uses identical names.
sql = re.sub(r"where conname = ('[^']+')", r"where connamespace = 'buykub'::regnamespace and conname = \1", sql)
header = '''-- Generated by scripts/build-buykub-schema.py. Apply only to a NEW schema.
-- Existing public/auth/storage tables are not changed.
begin;
do $$ begin
  if exists (select 1 from pg_namespace where nspname = 'buykub') then
    raise exception 'buykub already exists; use an explicit follow-up migration';
  end if;
end $$;
create schema buykub;
set local search_path = buykub, extensions, pg_catalog;
'''
footer = '''
-- No broad default grants; private tables remain protected by RLS.
revoke all on schema buykub from public;
revoke all on all tables in schema buykub from public, anon, authenticated;
grant usage on schema buykub to anon, authenticated, service_role;
grant select, insert, update, delete on all tables in schema buykub to authenticated;
grant all on all tables in schema buykub to service_role;
grant usage, select on all sequences in schema buykub to authenticated, service_role;
grant execute on all functions in schema buykub to service_role;

-- Published storefront fields only: payout fields remain owner-only.
drop policy "published shops are public" on buykub.shops;
create policy "published shops are public" on buykub.shops
  for select to anon using (published = true);
alter policy "owners manage their shop" on buykub.shops to authenticated;
grant select (id, owner_id, slug, name, bio, avatar_url, cover_url, accent_color, published, created_at)
  on buykub.shops to anon;
grant select on buykub.products, buykub.services to anon;
grant insert on buykub.shop_views, buykub.analytics_events to anon;

-- Only the trusted payment service may finalize payments.
revoke all on function buykub.finalize_stripe_checkout(uuid,text,text,text,text) from public, anon, authenticated;
revoke all on function buykub.expire_stripe_checkout(text) from public, anon, authenticated;
grant execute on function buykub.finalize_stripe_checkout(uuid,text,text,text,text) to service_role;
grant execute on function buykub.expire_stripe_checkout(text) to service_role;
drop policy "anyone can create a demo order" on buykub.orders;
drop policy "anyone can create a demo booking" on buykub.bookings;
notify pgrst, 'reload schema';
commit;
'''
out = root / 'supabase/bootstrap-buykub.sql'
out.write_text(header + sql + footer)
print(f'Built {out.name}: {len((header+sql+footer).splitlines())} lines')
