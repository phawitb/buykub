export type Purchase = {
  status: string;
  kind: string;
  order: { status: string; sessionId: string | null } | null;
  product: { deliveryType: string; filePath: string | null; fileName: string | null } | null;
  ownerId: string | null;
};
type Dependencies = {
  findPurchase: (sessionId: string) => Promise<Purchase | null>;
  sign: (path: string, expiresIn: number, fileName: string) => Promise<string>;
};
function json(body: unknown, status = 200) {
  return new Response(JSON.stringify(body), { status, headers: { 'content-type': 'application/json', 'cache-control': 'no-store', 'referrer-policy': 'no-referrer' } });
}
export function createDownloadHandler({ findPurchase, sign }: Dependencies) {
  return async (request: Request) => {
    if (request.method !== 'POST') return json({ error: 'Method not allowed' }, 405);
    let sessionId: unknown;
    try { ({ sessionId } = await request.json()); } catch { return json({ error: 'Invalid request' }, 400); }
    if (typeof sessionId !== 'string' || !/^(?:cs_(?:test_|live_)?[a-zA-Z0-9]{20,240}|pp_[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12})$/i.test(sessionId)) return json({ error: 'Invalid session' }, 400);
    try {
      const purchase = await findPurchase(sessionId);
      if (!purchase) return json({ error: 'ไม่พบรายการชำระเงิน' }, 404);
      if (purchase.status !== 'completed' || purchase.kind !== 'product' || purchase.order?.status !== 'paid' || purchase.order.sessionId !== sessionId) return json({ error: 'รายการนี้ยังไม่มีสิทธิ์ดาวน์โหลด' }, 403);
      const path = purchase.product?.filePath;
      if (purchase.product?.deliveryType !== 'file' || !path) return json({ error: 'ไม่พบไฟล์สินค้า' }, 404);
      // Storage paths are generated by our uploader. Reject URL metacharacters
      // before the service-role signer can normalize them across owner folders.
      if (!purchase.ownerId || !path.startsWith(`${purchase.ownerId}/`) || !/^[a-zA-Z0-9_./-]+$/.test(path) || path.split('/').some(part => !part || part === '..' || part === '.')) return json({ error: 'ไม่สามารถเข้าถึงไฟล์นี้' }, 403);
      const fileName = purchase.product.fileName || 'download';
      const url = await sign(path, 300, fileName);
      return json({ url, fileName, expiresIn: 300 });
    } catch { return json({ error: 'เตรียมดาวน์โหลดไม่สำเร็จ กรุณาลองอีกครั้ง' }, 503); }
  };
}
