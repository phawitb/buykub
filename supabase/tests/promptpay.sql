-- Isolated database only. All fixture rows roll back.
begin;
do $$
declare
  seller uuid:=gen_random_uuid(); shop uuid:=gen_random_uuid(); product uuid:=gen_random_uuid();
  ref uuid:=gen_random_uuid(); ref2 uuid:=gen_random_uuid(); race_ref uuid:=gen_random_uuid(); key_product uuid:=gen_random_uuid(); key_id uuid:=gen_random_uuid(); delivered record; replay record; denied boolean;
begin
  insert into auth.users(id,email,email_confirmed_at) values(seller,'buyer@example.com',now());
  perform set_config('request.jwt.claim.sub',seller::text,true);
  perform set_config('request.jwt.claims','{"app_metadata":{"provider":"google","providers":["google"]}}',true);
  insert into buykub.profiles(id) values(seller);
  insert into buykub.shops(id,owner_id,slug,name,published) values(shop,seller,'pp-'||shop,'PromptPay shop',true);
  insert into buykub.products(id,shop_id,slug,name,price_cents,delivery_type,published) values(product,shop,'file','Guide',10000,'file',true);
  perform buykub.begin_stripe_product_checkout(product,ref);
  perform buykub.prepare_promptpay_checkout(ref,'buyer@example.com');
  perform buykub.attach_promptpay_intent(ref,'pi_promptpay_regression');
  perform buykub.attach_promptpay_intent(ref,'pi_promptpay_regression');
  denied:=false;
  begin perform buykub.attach_promptpay_intent(ref,'pi_other'); exception when others then denied:=true; end;
  assert denied,'cannot swap a bound payment';
  denied:=false;
  begin perform buykub.finalize_promptpay_checkout(ref,'pi_other',10000,'thb'); exception when others then denied:=true; end;
  assert denied,'payment identity mismatch denied';
  denied:=false;
  begin perform buykub.finalize_promptpay_checkout(ref,'pi_promptpay_regression',100,'thb'); exception when others then denied:=true; end;
  assert denied,'underpayment denied';
  denied:=false;
  begin perform buykub.finalize_promptpay_checkout(ref,'pi_promptpay_regression',10000,'usd'); exception when others then denied:=true; end;
  assert denied,'wrong currency denied';
  assert (select count(*)=0 from buykub.orders where product_id=product),'invalid payment grants no delivery';
  select * into delivered from buykub.finalize_promptpay_checkout(ref,'pi_promptpay_regression',10000,'thb');
  select * into replay from buykub.finalize_promptpay_checkout(ref,'pi_promptpay_regression',10000,'thb');
  assert delivered.order_id=replay.order_id,'paid replay uses same order';
  assert delivered.email_token=replay.email_token,'retry preserves delivery token';
  assert (select buyer_email='buyer@example.com' and stripe_checkout_session_id like 'pp_%' from buykub.orders where id=delivered.order_id),'receipt and immutable email recorded';
  perform buykub.expire_promptpay_checkout(ref,'pi_promptpay_regression');
  assert (select status='completed' from buykub.stripe_checkout_contexts where checkout_reference=ref),'late failure cannot cancel paid order';
  perform buykub.sync_stripe_refund('pi_promptpay_regression',10000,10000,now());
  select * into replay from buykub.finalize_promptpay_checkout(ref,'pi_promptpay_regression',10000,'thb');
  assert replay.email_token is null,'refunded duplicate cannot deliver';
  assert (select status='refunded' from buykub.orders where id=delivered.order_id),'native refund revokes payment';
  perform buykub.begin_stripe_product_checkout(product,ref2);
  perform buykub.prepare_promptpay_checkout(ref2,'buyer@example.com');
  perform buykub.attach_promptpay_intent(ref2,'pi_promptpay_expired');
  denied:=false;
  begin perform buykub.expire_promptpay_checkout(ref2,'pi_other'); exception when others then denied:=true; end;
  assert denied,'only bound payment can release checkout';
  perform buykub.expire_promptpay_checkout(ref2,'pi_promptpay_expired');
  assert (select status='cancelled' from buykub.stripe_checkout_contexts where checkout_reference=ref2),'terminal payment releases checkout';
  -- Simulate a stale cleanup snapshot: NULL intent is observed, then checkout
  -- binds an intent before cleanup obtains the authoritative context row lock.
  insert into buykub.products(id,shop_id,slug,name,price_cents,delivery_type,published) values(key_product,shop,'key','Key',10000,'key',true);
  insert into buykub.product_keys(id,product_id,key_value,key_fingerprint,status) values(key_id,key_product,'race-secret','race-fingerprint','available');
  perform buykub.begin_stripe_product_checkout(key_product,race_ref);
  perform buykub.prepare_promptpay_checkout(race_ref,'buyer@example.com');
  update buykub.stripe_checkout_contexts set created_at=now()-interval '2 hours',promptpay_expires_at=now()-interval '1 hour' where checkout_reference=race_ref;
  perform buykub.attach_promptpay_intent(race_ref,'pi_cleanup_race');
  perform buykub.expire_unstarted_stripe_checkout(race_ref);
  assert (select status='created' and stripe_payment_intent_id='pi_cleanup_race' from buykub.stripe_checkout_contexts where checkout_reference=race_ref),'stale no-intent cleanup must preserve newly attached intent';
  assert (select status='reserved' from buykub.product_keys where id=key_id),'still payable QR keeps reserved stock';
  perform buykub.finalize_promptpay_checkout(race_ref,'pi_cleanup_race',10000,'thb');
  assert (select status='assigned' from buykub.product_keys where id=key_id),'racing payment can fulfill its reserved key';
  race_ref:=gen_random_uuid();
  perform buykub.begin_stripe_product_checkout(product,race_ref);
  update buykub.stripe_checkout_contexts set created_at=now()-interval '2 hours',promptpay_expires_at=now()-interval '1 hour' where checkout_reference=race_ref;
  perform buykub.attach_stripe_checkout_session(race_ref,'cs_free_race');
  perform buykub.expire_unstarted_stripe_checkout(race_ref);
  assert (select status='created' from buykub.stripe_checkout_contexts where checkout_reference=race_ref),'stale cleanup must preserve newly attached hosted free session';
  race_ref:=gen_random_uuid();
  perform buykub.begin_stripe_product_checkout(product,race_ref);
  perform buykub.prepare_promptpay_checkout(race_ref,'buyer@example.com');
  perform buykub.expire_unstarted_stripe_checkout(race_ref);
  assert (select status='created' from buykub.stripe_checkout_contexts where checkout_reference=race_ref),'fresh context cannot expire';
  update buykub.stripe_checkout_contexts set created_at=now()-interval '2 hours',promptpay_expires_at=now()-interval '1 hour' where checkout_reference=race_ref;
  perform buykub.expire_unstarted_stripe_checkout(race_ref);
  assert (select status='cancelled' from buykub.stripe_checkout_contexts where checkout_reference=race_ref),'truly unbound expired context can release';
  assert not has_function_privilege('anon','buykub.cancel_stripe_checkout(uuid)','EXECUTE'),'buyer cannot cancel a still payable QR';
  assert not has_function_privilege('authenticated','buykub.attach_promptpay_intent(uuid,text)','EXECUTE'),'buyer cannot replace payment identity';
  assert not has_function_privilege('authenticated','buykub.finalize_promptpay_checkout(uuid,text,integer,text)','EXECUTE'),'buyer cannot forge a paid event';
  assert has_function_privilege('service_role','buykub.finalize_promptpay_checkout(uuid,text,integer,text)','EXECUTE'),'webhook may finalize';
end $$;
rollback;
